"""Exact image coordinates in classical rational coinvariant algebras.

The Borel characteristic map has kernel generated by the positive-degree Weyl
invariants.  Passing from a parabolic flag to the full flag is injective over
QQ, so normal forms in the full coinvariant algebra detect exactly the same
relations among any selected Levi-invariant inputs.  No Schubert basis is
constructed here.

In type A the invariant ideal has the triangular Groebner basis
``h_i(x_i,...,x_N)`` (1 <= i <= N).  In types B/C it has the analogous basis
``h_i(x_i^2,...,x_n^2)``.  Their leading monomials in degrevlex are respectively
``x_i^i`` and ``x_i^(2*i)`` and are pairwise coprime.  The identities between
elementary and complete symmetric functions show that these generate the
usual invariant ideal.  Type D uses the elementary squared invariants AND
the Euler product; a Groebner basis is computed from those generators.
"""

from operator import index as integer_index

from sage.all import CartanType, PolynomialRing, QQ, prod

from .operations import complete_polynomial, elementary_polynomial


class CoinvariantEvaluator:
    """Cache exact coinvariant normal forms of selected generator monomials.

    ``image(exponents)`` returns a fresh sparse coefficient dictionary, indexed
    by coordinate exponent tuples.  Products use reduced cached parent images
    and reduced input-generator images, avoiding expansion of raw high powers.
    The constructor accepts only the standard Sage numbering of classical
    types.  Unsupported types raise ``NotImplementedError`` so callers may
    choose a different exact evaluator.
    """

    backend = "coinvariant"

    @classmethod
    def supports(cls, algebra):
        """Whether the input has the standard classical coordinate convention."""
        borel_map = algebra.borel_map
        kind = borel_map.cartan_type
        family = kind.type()
        rank = int(kind.rank())
        return (family in ("A", "B", "C", "D")
                and kind == CartanType([family, rank])
                and tuple(borel_map.nodes) == tuple(range(1, rank + 1)))

    def __init__(self, algebra, top_degree):
        borel_map = algebra.borel_map
        kind = borel_map.cartan_type
        family = kind.type()
        rank = int(kind.rank())
        if not self.supports(algebra):
            raise NotImplementedError(
                "coinvariant coordinates require standard-numbered type A, B, C or D")
        if isinstance(top_degree, bool):
            raise TypeError("top_degree must be a nonnegative integer")
        try:
            top_degree = int(integer_index(top_degree))
        except TypeError as error:
            raise TypeError("top_degree must be a nonnegative integer") from error
        if top_degree < 0:
            raise ValueError("top_degree must be nonnegative")

        self._family = family
        self._rank = rank
        self._top_degree = top_degree
        self._degrees = tuple(algebra.generator_degrees)
        size = rank + 1 if family == "A" else rank
        self.ring = PolynomialRing(QQ, size,
                                   names=["x{}".format(i + 1) for i in range(size)],
                                   order="degrevlex")
        coordinates = tuple(self.ring.gens())
        if family == "A":
            self._basis = tuple(complete_polynomial(self.ring, coordinates[i:], i + 1)
                                for i in range(size))
            self._basis_construction = "triangular complete symmetric invariants"
        elif family in ("B", "C"):
            squares = tuple(x * x for x in coordinates)
            self._basis = tuple(complete_polynomial(self.ring, squares[i:], i + 1)
                                for i in range(size))
            self._basis_construction = "triangular complete symmetric squared invariants"
        else:
            squares = tuple(x * x for x in coordinates)
            invariants = [elementary_polynomial(self.ring, squares, i)
                          for i in range(1, rank)]
            invariants.append(prod(coordinates))
            self._basis = tuple(self.ring.ideal(invariants).groebner_basis())
            self._basis_construction = "elementary squared invariants and Euler product"

        # A_r is represented in r+1 coordinates with sum zero.  Including the
        # trace correction makes this an actual weight-space embedding before
        # reduction, rather than merely equal modulo the first invariant.
        prefix = []
        total = self.ring.zero()
        for x in coordinates:
            total += x
            prefix.append(total)
        if family == "A":
            weight_images = tuple(prefix[i - 1] - QQ(i) / size * prefix[-1]
                                  for i in range(1, rank + 1))
        elif family == "B":
            weight_images = tuple(prefix[:rank - 1]) + (prefix[-1] / 2,)
        elif family == "C":
            weight_images = tuple(prefix)
        else:
            weight_images = tuple(prefix[:rank - 2]) + (
                (prefix[-2] - coordinates[-1]) / 2, prefix[-1] / 2)
        substitution = borel_map.ring.hom(weight_images, self.ring)
        self._reductions = 0
        self._cache_hits = 0
        self._generators = tuple(
            self._reduce(substitution(polynomial)) if degree <= top_degree
            else self.ring.zero()
            for polynomial, degree in zip(algebra.generator_polynomials, self._degrees))
        zero = (0,) * len(self._degrees)
        self._normal_forms = {zero: self.ring.one()}

    def _reduce(self, polynomial):
        self._reductions += 1
        return polynomial.reduce(self._basis)

    @staticmethod
    def key(index):
        """Return a deterministic comparable key for sparse elimination."""
        return tuple(index)

    def _exponents(self, exponents):
        exponents = tuple(exponents)
        if len(exponents) != len(self._degrees):
            raise ValueError("one exponent is required for each input generator")
        result = []
        for exponent in exponents:
            if isinstance(exponent, bool):
                raise TypeError("exponents must be nonnegative integers")
            try:
                exponent = int(integer_index(exponent))
            except TypeError as error:
                raise TypeError("exponents must be nonnegative integers") from error
            if exponent < 0:
                raise ValueError("exponents must be nonnegative")
            result.append(exponent)
        return tuple(result)

    def image(self, exponents):
        """Return exact normal-form coefficients for a generator monomial."""
        exponents = self._exponents(exponents)
        if exponents in self._normal_forms:
            self._cache_hits += 1
            return dict(self._normal_forms[exponents].dict())
        if sum(e * d for e, d in zip(exponents, self._degrees)) > self._top_degree:
            self._normal_forms[exponents] = self.ring.zero()
            return {}

        # Walk to a cached ancestor without recursion.  Prefer an immediate
        # cached parent, as the presentation staircase generally supplies one.
        path = []
        current = exponents
        while current not in self._normal_forms:
            candidates = []
            for position, exponent in enumerate(current):
                if exponent:
                    parent = list(current)
                    parent[position] -= 1
                    parent = tuple(parent)
                    candidates.append((parent, position))
                    if parent in self._normal_forms:
                        break
            parent, position = candidates[-1]
            path.append((current, parent, position))
            current = parent
        for current, parent, position in reversed(path):
            parent_image = self._normal_forms[parent]
            factor = self._generators[position]
            self._normal_forms[current] = (
                self._reduce(parent_image * factor) if parent_image and factor
                else self.ring.zero())
        return dict(self._normal_forms[exponents].dict())

    def metadata(self):
        """Return JSON-safe computational metadata, without claiming novelty."""
        return {
            "backend": self.backend,
            "family": self._family,
            "rank": self._rank,
            "coordinate_count": int(self.ring.ngens()),
            "coefficient_ring": "QQ",
            "normal_form_order": "degrevlex",
            "basis_construction": self._basis_construction,
            "groebner_basis_size": len(self._basis),
            "ambient_top_degree": self._top_degree,
            "cached_monomials": len(self._normal_forms),
            "normal_form_reductions": self._reductions,
            "cache_hits": self._cache_hits,
        }
