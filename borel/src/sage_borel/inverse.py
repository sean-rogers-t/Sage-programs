"""Exact polynomial lifts of Schubert classes over the rational numbers.

Two constructions are available.  ``linear`` inverts the Borel map on the
homogeneous Levi-invariant polynomials in the requested degree.  ``bgg`` starts
with the normalized positive-root discriminant and applies divided differences.
Neither construction asserts that a polynomial lift is unique: they provide
chosen sections of the Borel map, whose kernel is generated by positive-degree
global Weyl invariants in the Levi-invariant polynomial ring.

For our convention (rightmost divided difference applied first), the BGG lift
is ``partial_(w^-1*w0)(Delta / |W|)``.  If w is a minimal RIGHT parabolic coset
representative, this polynomial is already literally Levi-invariant.  For a
retained i the element w^-1*w0 has a left descent at i, so nil-Coxeter relations
give ``partial_i partial_(w^-1*w0) = 0``.  No averaging over a Weyl group occurs.
"""

from math import comb

from sage.all import IntegerVectors, QQ, RootSystem, identity_matrix, matrix, prod

from .expansion import Expansion


class InverseMixin:
    """Schubert basis elements and exact inverse Borel calculations."""

    @staticmethod
    def _inverse_method(method):
        if method not in ("auto", "linear", "bgg"):
            raise ValueError("method must be 'auto', 'linear' or 'bgg'")
        return method

    def _clear_inverse_caches(self):
        """Discard polynomial lifts, degreewise inverses and the discriminant."""
        self._inverse_polynomials = {}
        self._inverse_linear_degrees = {}
        self._inverse_discriminant = None

    def _inverse_caches(self):
        if not hasattr(self, "_inverse_polynomials"):
            self._clear_inverse_caches()

    def _inverse_index(self, word):
        element = self._coerce_weyl(word)
        if not self._is_minimal(element):
            raise ValueError("Weyl element is not a minimal right-coset representative")
        return element

    def schubert(self, word):
        """Return the single Schubert class indexed by ``word``.

        Words use Dynkin nodes in multiplication order.  The index must be a
        minimal right-coset representative for this map's parabolic quotient.
        The empty word is the cohomological unit.
        """
        return self._expansion({self._inverse_index(word): QQ.one()})

    def _effective_inverse_method(self, degree, method):
        if method != "auto":
            return method
        # Degreewise inversion handles even E7/E8 low degrees without expanding
        # the high-degree global discriminant.  For smaller root systems, the
        # discriminant is useful when the degreewise monomial space grows large.
        monomial_count = comb(self.rank + degree - 1, degree)
        if monomial_count <= 150:
            return "linear"
        if self._longest is None:
            self._longest = self.W.long_element()
        root_count = int(self._longest.length())
        discriminant_bound = comb(self.rank + root_count - 1, root_count)
        return "bgg" if discriminant_bound <= 20000 else "linear"

    def _linear_inverse_degree(self, degree):
        """Construct an exact invariant-polynomial section in one degree."""
        self._inverse_caches()
        if degree in self._inverse_linear_degrees:
            return

        exponents = tuple(tuple(int(e) for e in values)
                          for values in IntegerVectors(degree, self.rank))
        monomials = tuple(self.ring({exponent: QQ.one()}) for exponent in exponents)
        positions = {exponent: position for position, exponent in enumerate(exponents)}
        size = len(monomials)

        if self.retained_nodes:
            # Stack all maps 1-s_i.  Its kernel consists precisely of the
            # degree-d polynomials invariant under the generators of W_P.
            constraints = {}
            for block, node in enumerate(self.retained_nodes):
                for column, monomial in enumerate(monomials):
                    difference = monomial - self.reflect(monomial, node)
                    for exponent, coefficient in difference.dict().items():
                        row = block * size + positions[tuple(exponent)]
                        constraints[row, column] = coefficient
            invariance = matrix(QQ, len(self.retained_nodes) * size, size,
                                constraints, sparse=True)
            invariant_basis = tuple(
                self.ring(sum(coefficient * monomial
                              for coefficient, monomial in zip(vector, monomials)
                              if coefficient))
                for vector in invariance.right_kernel().basis())
        else:
            invariant_basis = monomials

        schubert_basis = self.basis(degree)
        rows = {element: position for position, element in enumerate(schubert_basis)}
        entries = {}
        for column, polynomial in enumerate(invariant_basis):
            self._validate_invariance(polynomial)
            for element, coefficient in self.expand(polynomial).items():
                if element not in rows:
                    raise ArithmeticError("a homogeneous Borel image has an unexpected degree")
                entries[rows[element], column] = coefficient
        coefficient_map = matrix(QQ, len(schubert_basis), len(invariant_basis),
                                 entries, sparse=True)
        if coefficient_map.rank() != len(schubert_basis):
            raise ArithmeticError("the invariant-polynomial Borel map is not surjective")
        target = identity_matrix(QQ, len(schubert_basis), sparse=True)
        solutions = coefficient_map.solve_right(target)
        if coefficient_map * solutions != target:
            raise ArithmeticError("inverse Borel linear equations did not solve exactly")

        # Store all columns because solving the same degree again is wasteful.
        lifts = {}
        for column, element in enumerate(schubert_basis):
            polynomial = self.ring(sum(solutions[row, column] * invariant_basis[row]
                                       for row in range(len(invariant_basis))
                                       if solutions[row, column]))
            self._validate_invariance(polynomial)
            if not polynomial or polynomial.total_degree() != degree:
                raise ArithmeticError("inverse Borel lift has an unexpected degree")
            lifts[element] = polynomial
        for element, polynomial in lifts.items():
            self._inverse_polynomials["linear", element] = polynomial
        self._inverse_linear_degrees[degree] = tuple(schubert_basis)

    def _bgg_inverse_polynomial(self, element):
        if self._inverse_discriminant is None:
            roots = RootSystem(self.cartan_type).root_lattice().positive_roots()
            root_polynomials = (
                self.ring(sum(coefficient * self.simple_roots[int(node)]
                              for node, coefficient in root.monomial_coefficients().items()))
                for root in roots)
            self._inverse_discriminant = self.ring(
                prod(root_polynomials) / self.W.cardinality())
        if self._longest is None:
            self._longest = self.W.long_element()
        polynomial = self._inverse_discriminant
        operator = element.inverse() * self._longest
        for node in reversed(self._word(operator)):
            polynomial = self.divided_difference(polynomial, node)
        self._validate_invariance(polynomial)
        if not polynomial or polynomial.total_degree() != element.length():
            raise ArithmeticError("BGG polynomial lift has an unexpected degree")
        return self.ring(polynomial)

    def schubert_polynomial(self, word, method="auto"):
        r"""Return a homogeneous Levi-invariant polynomial lifting one class.

        ``expand(schubert_polynomial(w)) == schubert(w)``.  ``linear`` solves
        the Borel coefficient equations in the requested homogeneous degree;
        ``bgg`` applies divided differences to the normalized positive-root
        discriminant.  ``auto`` selects by estimates of the polynomial spaces.

        Polynomial representatives are not unique.  Different methods may
        return different representatives of the same rational cohomology class.
        Low-degree calculations avoid constructing the global discriminant;
        large homogeneous spaces can nevertheless require substantial memory.
        """
        method = self._inverse_method(method)
        element = self._inverse_index(word)
        self._inverse_caches()
        degree = int(element.length())
        if degree == 0:
            return self.ring.one()
        if degree == 1:
            node = self._word(element)[0]
            return self.weights[self._node_positions[node]]

        effective = self._effective_inverse_method(degree, method)
        key = (effective, element)
        if key not in self._inverse_polynomials:
            if effective == "linear":
                self._linear_inverse_degree(degree)
            else:
                self._inverse_polynomials[key] = self._bgg_inverse_polynomial(element)
        return self._inverse_polynomials[key]

    def lift(self, expansion, method="auto"):
        """Lift a possibly inhomogeneous Schubert expansion to a polynomial.

        The argument must be an ``Expansion`` in the same flag-variety context.
        The result is literally Levi-invariant and maps back to the given
        expansion.  Zero lifts to zero.  See ``schubert_polynomial`` for the
        available methods and the nonuniqueness of polynomial representatives.
        """
        method = self._inverse_method(method)
        if not isinstance(expansion, Expansion):
            raise TypeError("expansion must be a Schubert Expansion")
        self._expansion()._check_context(expansion)
        return self.ring(sum(coefficient * self.schubert_polynomial(element, method=method)
                             for element, coefficient in expansion.items()))
