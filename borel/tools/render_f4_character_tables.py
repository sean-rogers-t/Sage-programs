"""Render the exact saved F4 character-image tables; Python standard library."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def factored(n):
    if n == 1:
        return "1"
    answer = []
    for p in (2, 3):
        e = 0
        while n % p == 0:
            n //= p
            e += 1
        if e:
            answer.append(str(p) if e == 1 else "{}^{}".format(p, e))
    assert n == 1, "unexpected prime in the exhaustive F4 table"
    return " ".join(answer)


def main():
    data = json.loads((ROOT/'experiments/f4-character-form-results.json').read_text())
    assert data['result'] == 'passed'
    lines = [
        "# Complete F4 character-image Smith tables", "",
        "These are the full images of Sym_Z(6 Q_long)^(W_L), as proved in",
        "[the character-form note](F4_CHARACTER_FORM.md). Degree d means H^(2d).",
        "The factors describe H^(2d)(F4/P_i,Z)/J_i^d; all images have full rational rank.",
        "Products such as `2^4 3^2` mean 2^4 times 3^2. Unit factors are retained.", "",
        "The comparison uses embedded Schubert lattices. `yes/no` in the last",
        "column means character contained in catalogue, catalogue not contained",
        "in character. The primitive-image form has the same containment outcomes",
        "in every row. Exact quotient factors, sums and intersections are in",
        "[the JSON certificate](experiments/f4-character-form-results.json).", "",
        "Generated by [the table renderer](tools/render_f4_character_tables.py).", ""]
    for case in data['cases']:
        lines.extend(["## F4/P{}".format(case['parabolic']), "",
                      "| d | Source rank | Smith factors | Character in catalogue / converse |",
                      "|---:|---:|---|---|"])
        for row in case['degrees']:
            comparison = row['comparisons'][0]
            flags = (comparison['old_contains_character'], comparison['character_contains_old'])
            assert all((c['old_contains_character'], c['character_contains_old']) == flags
                       for c in row['comparisons'])
            lines.append("| {} | {} | {} | {} |".format(
                row['degree'], len(row['monomial_exponents']),
                ", ".join(factored(n) for n in row['smith_factors']),
                "/".join("yes" if flag else "no" for flag in flags)))
        lines.append("")
    lines.extend(["All higher cohomology groups vanish. The source algebra continues in higher degrees.",
                  "Only primes 2 and 3 occur in these exhaustive image tables.",
                  "This is a statement about this representation and these four parabolics.", ""])
    (ROOT/'F4_CHARACTER_TABLES.md').write_text("\n".join(lines))
    print("Rendered", data['degree_rows'], "rows")


if __name__ == '__main__':
    main()
